// Run against a disposable LeadDesk instance. Only generated /tmp fixtures are indexed.
import { chromium } from '../apps/web/node_modules/playwright-core/index.mjs';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, renameSync, rmSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const base = process.env.LEADDESK_TEST_URL || 'http://127.0.0.1:8765';
const tokenFile = process.env.LEADDESK_TEST_TOKEN_FILE || resolve('../../.local/access-token');
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true });
const fixture = mkdtempSync(join(tmpdir(), 'leaddesk-files-smoke-'));
const scope = `files-smoke-${Date.now()}`;
let approvedId;
let page;
let token;
try {
  const initial = join(fixture, 'proposal.txt');
  const moved = join(fixture, 'renamed.txt');
  writeFileSync(initial, 'Synthetic clinic appointment proposal. <script>untrusted fixture</script>');
  writeFileSync(join(fixture, 'proposal-other.txt'), 'Synthetic unrelated proposal.');
  writeFileSync(join(fixture, 'unsupported.pdf'), '%PDF fixture without supported text extraction');
  token = readFileSync(tokenFile, 'utf8').trim();
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.getByLabel('Local access key').fill(token);
  await page.getByRole('button', { name: 'Unlock workspace' }).click();
  await page.getByRole('button', { name: 'More tools', exact: true }).click();
  await page.getByRole('button', { name: 'Files and memory', exact: true }).click();
  await page.getByLabel('Folder path to approve').fill(fixture);
  const approval = page.waitForResponse(response => response.url().endsWith('/v1/files/roots') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Approve folder', exact: true }).click();
  approvedId = (await (await approval).json()).id;
  await page.getByText('Folder approved. Choose Reconcile folder to index it.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Reconcile folder', exact: true }).click();
  await page.getByText('Folder reconciled. Search the current snapshot.', { exact: true }).waitFor();
  await page.getByLabel('Filename or text keywords').fill('proposal');
  await page.getByRole('button', { name: 'Search approved files', exact: true }).click();
  await page.locator('.file-match').first().waitFor();
  assert.equal(await page.locator('.file-match').count(), 2);
  const target = page.locator('.file-match').filter({ has: page.getByRole('heading', { name: 'proposal.txt', exact: true }) });
  await target.getByRole('button', { name: 'Preview file', exact: true }).click();
  await page.locator('.file-preview').waitFor();
  assert.match(await page.locator('.file-preview pre').innerText(), /<script>untrusted fixture<\/script>/);
  assert.equal(await page.locator('.file-preview script').count(), 0);
  await page.getByLabel('Reason for file correction').fill('Synthetic browser wrong-file check.');
  await target.getByRole('button', { name: 'Wrong file', exact: true }).click();
  await page.getByText('File correction saved for this query and folder.', { exact: true }).waitFor();
  assert.equal(await page.locator('.file-match').count(), 1);
  await page.getByText('Saved file corrections (1)', { exact: true }).click();
  await page.getByRole('button', { name: 'Undo file correction', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.file-match').length === 2);
  renameSync(initial, moved);
  await page.getByRole('button', { name: 'Search approved files', exact: true }).click();
  await page.getByText('1 stale matches omitted. Reconcile this folder.', { exact: true }).waitFor();
  assert.equal(await page.locator('.file-match').count(), 1);
  await page.getByRole('button', { name: 'Reconcile folder', exact: true }).click();
  await page.getByText('Folder reconciled. Search the current snapshot.', { exact: true }).waitFor();
  await page.getByLabel('Filename or text keywords').fill('appointment');
  await page.getByRole('button', { name: 'Search approved files', exact: true }).click();
  await page.getByRole('heading', { name: 'renamed.txt', exact: true }).waitFor();
  unlinkSync(moved);
  await page.getByRole('button', { name: 'Preview file', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'moved, was deleted' }).waitFor();
  assert.equal(await page.locator('.file-preview').count(), 0);
  await page.route('**/v1/files/search', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Synthetic file search outage' }) }));
  await page.getByRole('button', { name: 'Search approved files', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Synthetic file search outage' }).waitFor();
  await page.unroute('**/v1/files/search');
  await page.getByLabel('Filename or text keywords').fill('unsupported');
  await page.getByRole('button', { name: 'Search approved files', exact: true }).click();
  await page.getByRole('heading', { name: 'unsupported.pdf', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Preview file', exact: true }).isDisabled(), true);
  await page.getByLabel('Memory scope', { exact: true }).fill(scope);
  await page.getByRole('button', { name: 'Load memory scope', exact: true }).click();
  await page.getByRole('heading', { name: 'Add a scoped note', exact: true }).waitFor();
  await page.getByLabel('Memory content').fill('Synthetic local project note');
  await page.getByLabel('Pin this note').check();
  await page.getByRole('button', { name: 'Save scoped memory', exact: true }).click();
  await page.getByText('Scoped memory saved.', { exact: true }).waitFor();
  assert.equal(await page.locator('.memory-note').count(), 1);
  await page.getByRole('button', { name: 'Edit note', exact: true }).click();
  await page.getByLabel('Memory content').fill('Corrected synthetic local project note');
  await page.getByRole('button', { name: 'Save scoped memory', exact: true }).click();
  await page.getByText('Corrected synthetic local project note', { exact: true }).waitFor();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export scoped notes', exact: true }).click();
  const noteExport = JSON.parse(readFileSync(await (await download).path(), 'utf8'));
  assert.equal(noteExport.items[0].revision, 2);
  await page.getByRole('button', { name: 'Website research', exact: true }).click();
  await page.getByRole('button', { name: 'Files and memory', exact: true }).click();
  assert.match(await page.locator('.memory-note').innerText(), /Corrected synthetic/);
  await page.reload();
  await page.getByRole('button', { name: 'Files and memory', exact: true }).click();
  await page.getByLabel('Search folder').selectOption(approvedId);
  await page.getByLabel('Memory scope', { exact: true }).fill(scope);
  await page.getByRole('button', { name: 'Load memory scope', exact: true }).click();
  await page.locator('.memory-note').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.getByRole('button', { name: 'Delete note', exact: true }).click();
  await page.getByText('Note deleted.', { exact: true }).waitFor();
  assert.equal(await page.locator('.memory-note').count(), 0);
  await page.getByRole('button', { name: 'Revoke folder approval', exact: true }).click();
  await page.getByRole('button', { name: 'Remove folder index', exact: true }).click();
  await page.getByText('Folder approval, indexed text and file corrections removed.', { exact: true }).waitFor();
  assert.equal(await page.locator('.file-match').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: explicit folder approval, text previews, wrong-file/undo, moved/deleted files, unsupported status, error/retry, memory edit/export/delete, persistence and mobile layout');
} finally {
  if (page && token) {
    const headers = { Authorization: `Bearer ${token}` };
    if (approvedId) await page.request.delete(`${base}/v1/files/roots/${approvedId}`, { headers }).catch(() => {});
    await page.request.delete(`${base}/v1/memories/scope?scope=${encodeURIComponent(scope)}`, { headers }).catch(() => {});
  }
  rmSync(fixture, { recursive: true, force: true });
  await browser.close();
}
