# Words that describe what the seller makes, not who buys it ("we build websites for ...").
SELLER_WORDS = {'web', 'website', 'websites', 'online', 'software', 'app', 'apps', 'design', 'marketing', 'service', 'services',
                'system', 'platform', 'solution', 'solutions', 'office', 'shop', 'store', 'agency', 'company', 'business', 'it',
                'builder', 'tool', 'tools'}
WIDE_SCRIPT = re.compile(r'[\u3040-\u30ff\u3400-\u9fff\uac00-\ud7af\u0e00-\u0e7f]')  # scripts written without spaces


def singular(word):
    if len(word) > 4 and word.endswith('ies'):
        return word[:-3] + 'y'
    return word[:-2] if word.endswith(('ches', 'shes', 'sses', 'xes')) else word[:-1] if len(word) > 4 and word.endswith('s') and not word.endswith('ss') else word


def phrases(text, longest=4):
    """Every 1-4 word phrase of the text, also with the last word in singular ("hair salons" -> "hair salon")."""
    tokens = re.findall(r'[\w\'-]+', fold_text(text))
    grams = set()
    for n in range(1, longest + 1):
        for i in range(len(tokens) - n + 1):
            words_ = tokens[i:i + n]
            grams |= {' '.join(words_), ' '.join(words_[:-1] + [singular(words_[-1])])}
    return grams


def term_found(term, grams, folded, strong):
    """Names (any language) may match as one word; synonyms must be phrases, which avoids "estate" -> notary."""
    if WIDE_SCRIPT.search(term):
        return len(term) >= 3 and term in folded
    one_word = ' ' not in term
    return (len(term) >= 4 and term in grams and term not in SELLER_WORDS and term not in STOPWORDS
            and (strong or not one_word))


def search_categories(query, limit=30):
    """Rank catalogue entries for a typed query in any catalogue language. Deterministic."""
    q = fold_text(query)
    if len(q) < 2:
        return []
    scored = []
    for key, (label, group, _) in CATEGORIES.items():
        best, matched = 0, None
        for position, term in enumerate(SEARCH_TERMS.get(key) or [fold_text(label)]):
            score = (100 if term == q else 70 if term.startswith(q) else
                     45 if re.search(r'(?<!\w)' + re.escape(q), term) else
                     25 if len(q) >= 3 and ' ' not in q and q in term else 0)  # inside compounds: "schneider"
            score -= 5 if position else 0  # the label itself ranks above its synonyms
            if score > best:
                best, matched = score, term
        if not best and ' ' in q:
            # Every word of a multi-word query starts a word somewhere in its names ("wedding hall" -> events venue).
            words_ = {w for term in SEARCH_TERMS.get(key) or [] for w in term.split()}
            hits = [next((w for w in words_ if w.startswith(singular(part))), None) for part in q.split()]
            if all(hits):
                best, matched = 20, ' + '.join(hits)
        if best > 0:
            scored.append((-best - (3 if key in CURATED else 0), label.casefold(), key, matched))
    return [{'id': key, 'label': CATEGORIES[key][0], 'group': CATEGORIES[key][1], 'matched': matched,
             'source': 'curated' if key in CURATED else 'osm_preset'} for _, _, key, matched in sorted(scored)[:limit]]


def catalogue_suggestions(text, exclude=(), limit=12):
    """Business types whose name or synonym appears as a phrase in the offer text."""
    grams, folded, found = phrases(text), fold_text(text), []
    for key, (label, _, _) in CURATED.items():
        # "Cafés and coffee shops" -> "café", "coffee shop"; matched like names.
        parts = [singular(w) if ' ' not in w else ' '.join(w.split()[:-1] + [singular(w.split()[-1])])
                 for w in re.split(r'\s*(?:,| and )\s*', fold_text(label)) if w]
        hit = next((t for t in parts if key not in exclude and term_found(t, grams, folded, True)), None)
        if hit:
            found.append((-1, -len(hit), 0, key, hit))
    for item in CATALOGUE['items']:
        if item['id'] in exclude:
            continue
        # A phrase that is another preset's English name belongs to that preset ("coffee shop" is not Dutch cannabis).
        owns = lambda t: item['id'] in ENGLISH_OWNERS.get(t, {item['id']})
        hit = next((t for t in item['names'] if owns(t) and term_found(t, grams, folded, True)), None)
        rank_ = 0 if hit else 1
        hit = hit or next((t for t in item['search'] if owns(t) and term_found(t, grams, folded, False)), None)
        if hit:
            # Names before synonyms, longer phrases first, then shorter preset ids (general before specialised).
            found.append((rank_, -len(hit), item['id'].count('/'), item['id'], hit))
    return [(key, hit) for *_, key, hit in sorted(found)[:limit]]


class _Text(HTMLParser):
    SKIP = {'script', 'style', 'noscript', 'template', 'svg'}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.depth, self.parts, self.title, self.meta, self.in_title = 0, [], [], [], False

    def handle_starttag(self, tag, attrs):
        if tag in self.SKIP:
            self.depth += 1
        self.in_title = tag == 'title'
        attrs = dict(attrs)
        if tag == 'meta' and (attrs.get('name') or attrs.get('property') or '').lower() in {'description', 'og:description', 'keywords'}:
            self.meta.append(attrs.get('content') or '')

    def handle_endtag(self, tag):
        if tag in self.SKIP and self.depth:
            self.depth -= 1
        if tag == 'title':
            self.in_title = False

    def handle_data(self, data):
        if self.in_title:
            self.title.append(data)
        elif not self.depth:
            self.parts.append(data)


def page_text(html):
    parser = _Text()
    parser.feed(html[:1_000_000])
    clean = lambda values: ' '.join(' '.join(values).split())
    return {'title': clean(parser.title)[:300], 'description': clean(parser.meta)[:600], 'text': clean(parser.parts)[:20000]}


def words(text):
    return [w for w in re.findall(r"[a-zà-ÿ][a-zà-ÿ0-9'-]{1,30}", text.casefold()) if w not in STOPWORDS and len(w) > 2]


def profile_offer(offer, page=None):
    """Keyword profile of the user's own offer and (optionally) their website."""
    counts = Counter(words(offer) * 3)
    site = None
    if page is not None:
        site = page_text(page.html)
        counts.update(words(site['title']) * 3 + words(site['description']) * 2 + words(site['text']))
    keywords = [w for w, _ in counts.most_common(25)]
    found = set(keywords) | set(words(offer))
    suggested, reasons = [], []
    for trigger, categories in SUGGESTIONS:
        hits = sorted(found & trigger)
        if hits:
            for category in categories:
                if category not in suggested:
                    suggested.append(category)
            reasons.append(f"{', '.join(hits)} → {', '.join(CATEGORIES[c][0] for c in categories)}")
    text = ' '.join([offer] + ([site['title'], site['description']] if site else []))
    for key, hit in catalogue_suggestions(text, exclude=set(suggested)):
        if len(suggested) >= MAX_CATEGORIES:
            break
        if not any(key in CATEGORIES and CATEGORIES[key][2][0] in CATEGORIES[c][2] for c in suggested):
            suggested.append(key)
            reasons.append(f'"{hit}" → {CATEGORIES[key][0]}')
    web = bool(found & WEB_PRESENCE) or 'web design' in offer.casefold()
    return {'keywords': keywords, 'suggested_categories': suggested, 'suggestion_reasons': reasons,
            'offer_kind': 'web_presence' if web else 'general',
            'website': None if page is None else {'url': page.url, 'title': site['title'], 'description': site['description']},
            'method': 'keyword_profile_v2', 'model_used': False}


