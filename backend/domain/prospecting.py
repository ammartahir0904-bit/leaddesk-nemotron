class ProspectSearchInput(LocalInput):
    offer: str = Field(min_length=3, max_length=2000)
    location: str = Field(min_length=2, max_length=200)
    categories: list[str] = Field(default_factory=list, max_length=MAX_CATEGORIES)
    name_keyword: str | None = Field(default=None, min_length=2, max_length=40)
    limit: int = Field(default=40, ge=1, le=300)
    # Explicit per-request consent to query public OpenStreetMap services.
    use_public_osm: bool = Field(strict=True)
    # Explicit per-request consent to read the public Overture Maps release (Amazon S3) for this area.
    use_overture: bool = Field(default=False, strict=True)

    @field_validator('categories')
    @classmethod
    def known(cls, value):
        if len(set(value)) != len(value) or any(item not in CATEGORIES for item in value):
            raise ValueError('Choose distinct categories from the catalogue.')
        return value

    @field_validator('name_keyword')
    @classmethod
    def plain(cls, value):
        if value is not None and not re.fullmatch(r"[\w][\w '-]*", value):
            raise ValueError('Use letters, numbers, spaces, hyphens or apostrophes only.')
        return value

    @model_validator(mode='after')
    def scope(self):
        if not self.use_public_osm:
            raise ValueError('Confirm that this search may query public OpenStreetMap services.')
        if not self.categories and not self.name_keyword:
            raise ValueError('Choose at least one business type or a name keyword.')
        return self


def overpass_query(area, categories, name_keyword, limit):
    """area: ('area', id) or ('around', lat, lon, metres). Inputs are validated above."""
    scope = f'(area.a)' if area[0] == 'area' else f'(around:{int(area[3])},{float(area[1])},{float(area[2])})'
    name = f'["name"~"{name_keyword.replace(chr(39), ".")}",i]' if name_keyword else '["name"]'
    filters = list(dict.fromkeys(tuple(f.items()) for c in categories for f in CATEGORIES[c][2])) if categories else [((k, None),) for k in BUSINESS_KEYS]
    tag = lambda k, v: f'["{k}"="{v}"]' if v else f'["{k}"]'
    lines = [f"  nwr{''.join(tag(k, v) for k, v in pairs)}{name}{scope};" for pairs in filters]
    head = f'area({area[1]})->.a;\n' if area[0] == 'area' else ''
    return f'[out:json][timeout:25];\n{head}(\n' + '\n'.join(lines) + f'\n);\nout center tags {int(limit) * 3};'


def category_of(tags, categories):
    """The most specific matching category (most tags matched), among the chosen ones when given."""
    best, size = None, 0
    for category in categories or CATEGORIES:
        for wanted in CATEGORIES[category][2]:
            if len(wanted) > size and all(tags.get(k) == v for k, v in wanted.items()):
                best, size = category, len(wanted)
    return best


def nominatim_filters(categories):
    """(key, value) pairs for the Nominatim fallback, which can only filter on the main tag."""
    if not categories:
        return [(k, None) for k in BUSINESS_KEYS]
    pairs = [next(((k, v) for k, v in f.items() if k in BUSINESS_KEYS), next(iter(f.items())))
             for c in categories for f in CATEGORIES[c][2]]
    return list(dict.fromkeys(pairs))


def candidate(element, offer_kind, categories, retrieved_at):
    tags = element.get('tags') or {}
    name = (tags.get('name') or '').strip()
    if not name:
        return None
    lat = element.get('lat', (element.get('center') or {}).get('lat'))
    lon = element.get('lon', (element.get('center') or {}).get('lon'))
    get = lambda *keys: next((tags[k].strip() for k in keys if tags.get(k, '').strip()), None)
    website = get('website', 'contact:website', 'url')
    if website and not re.match(r'https?://', website, re.I):
        website = 'https://' + website
    phone, email = get('phone', 'contact:phone', 'contact:mobile'), get('email', 'contact:email')
    address = ', '.join(v for v in (get('addr:housenumber'), get('addr:street'), get('addr:suburb'), get('addr:city'), get('addr:postcode')) if v) or None
    points, reasons, needs = 0, [], []
    social_only = bool(website) and classify(website)[0] != 'website'
    if offer_kind == 'web_presence':
        if social_only:
            points += 2
            needs.append(f'The listed website is only their {classify(website)[1]} page: no own website listed. A possible need; verify.')
        elif website:
            needs.append('Has a website listed. Check whether it already covers your offer.')
        else:
            points += 2
            needs.append('No website listed in OpenStreetMap: a possible need. Verify; OSM data may be incomplete.')
    for value, label in ((phone, 'phone'), (email, 'email'), (website, 'social page' if social_only else 'website')):
        if value:
            points += 1
            reasons.append(f'{label} listed')
    if address:
        reasons.append('address listed')
    budget_signals = []
    if get('brand', 'brand:wikidata'):
        budget_signals.append(f"Part of a brand or chain ({get('brand') or get('brand:wikidata')}).")
    kind, ident = element.get('type'), element.get('id')
    category = category_of(tags, categories)
    return {'id': f'{kind}/{ident}', 'name': name, 'category': category,
            'category_label': CATEGORIES[category][0] if category else 'Named business',
            'address': address, 'phone': phone, 'email': email, 'website': website, 'website_is_social': social_only,
            'opening_hours': get('opening_hours'), 'lat': lat, 'lon': lon,
            'need_signals': needs, 'priority_points': points, 'priority_reasons': reasons,
            'budget': None, 'budget_reason': 'Budget is unknown; nothing public establishes what this business can afford.',
            'budget_signals': budget_signals,
            'evidence': {'source': 'OpenStreetMap', 'url': f'https://www.openstreetmap.org/{kind}/{ident}',
                         'retrieved_at': retrieved_at, 'licence': 'ODbL — © OpenStreetMap contributors'}}


def rank(elements, offer_kind, categories, limit, retrieved_at):
    seen, items, skipped = set(), [], 0
    for element in elements:
        item = candidate(element, offer_kind, categories, retrieved_at)
        if item is None:
            skipped += 1
            continue
        # The same business is often mapped twice (e.g. as a point and a building).
        where = item['address'] or item['phone'] or (round(item['lat'] or 0, 3), round(item['lon'] or 0, 3))
        key = (item['name'].casefold(), where)
        if key in seen:
            continue
        seen.add(key)
        items.append(item)
    items.sort(key=lambda item: (-item['priority_points'], item['name'].casefold(), item['id']))
    return items[:limit], {'returned_elements': len(elements), 'unnamed_skipped': skipped, 'kept': min(len(items), limit),
                           'over_limit': max(0, len(items) - limit)}


def own_website(item):
    """The listed website only when it is the business's own site, not an Instagram/Facebook page or directory."""
    website = item.get('website')
    return website if website and classify(website)[0] == 'website' else None


def keyword_hits(keywords, texts):
    body = ' '.join(texts).casefold()
    return [k for k in keywords if re.search(r'(?<!\w)' + re.escape(k) + r'(?!\w)', body)]
